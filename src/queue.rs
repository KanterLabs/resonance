/// The queue determines the playback order of [Playable] items, and is also used to control
/// playback itself.
pub struct Queue {
    /// The internal data, which doesn't change with shuffle or repeat. This is
    /// the raw data only.
    pub queue: Arc<RwLock<Vec<Playable>>>,
    rpc_mutation: Mutex<u64>,
    /// The playback order of the queue, as indices into `self.queue`.
    random_order: RwLock<Option<Vec<usize>>>,
    current_track: RwLock<Option<usize>>,
    spotify: Spotify,
    cfg: Arc<Config>,
    library: Arc<Library>,
    listening: Mutex<crate::recommendations::tracker::Tracker>,
    /// URIs observed in this process. This intentionally survives queue edits so a
    /// local radio station cannot reintroduce a track after it has been removed.
    session_played: Mutex<HashSet<String>>,
    /// Song identities observed in this process. Unlike URI history this keeps
    /// alternate Spotify releases of one song from re-entering radio.
    session_song_keys: Mutex<HashSet<String>>,
    /// Raw queue indices explicitly selected by the user. Indices are adjusted
    /// alongside queue edits so a duplicate occurrence remains independently
    /// eligible for playback.
    explicit_queued: RwLock<HashSet<usize>>,
    /// Every raw queue index generated by local radio, including older stations.
    /// This is provenance that is persisted with the queue.
    radio_generated: RwLock<HashSet<usize>>,
    /// Raw queue indices generated by the currently active station generation.
    /// Older radio entries remain in the raw queue but are parked while a station
    /// is active and become ordinary retained context after cancellation.
    active_radio: RwLock<HashSet<usize>>,
    /// Queue entries already selected for playback in this terminal session.
    /// This preserves per-entry identity so a newly queued duplicate remains an
    /// explicit user choice even when its URI was played earlier.
    played_indices: RwLock<HashSet<usize>>,
    /// Monotonic identity for the exact current queue occurrence. This rejects
    /// delayed radio fills after remove/reinsert ABA at the same raw index.
    current_token: RwLock<u64>,
    /// Future raw entries parked when a station starts. Radio batches are
    /// appended after that context, so this continuation keeps those entries
    /// reachable if playback advances past them before the station is stopped.
    resume_context: RwLock<Vec<usize>>,
    /// Distinguishes an intentionally empty captured continuation from a
    /// station that has never owned the queue lane.
    resume_context_valid: RwLock<bool>,
    radio: Mutex<RadioState>,
    last_skip: Mutex<Option<SkipSnapshot>>,
}

/// One undo entry for an exact queue occurrence, valid only until another selection/edit.
struct SkipSnapshot {
    index: usize,
    revision: String,
    after_token: u64,
    position_ms: u32,
    playing: bool,
}

/// State shared by radio workers and the UI thread. Holding this lock while a
/// radio batch is applied makes cancellation/generation checks atomic with the
/// queue insertion.
#[derive(Default)]
struct RadioState {
    generation: u64,
    active: bool,
    seed: Option<String>,
    seed_track: Option<Track>,
    in_flight: bool,
    retry_at: Option<Instant>,
    retry_attempt: u8,
    waiting: bool,
    natural_end: bool,
    refresh_requested: bool,
}

const RADIO_RETRY_BASE: Duration = Duration::from_secs(1);
const RADIO_RETRY_MAX: Duration = Duration::from_secs(60);

/// A single-flight radio request is tied to the exact queue occurrence that was
/// current when it was claimed. The original station seed is carried separately
/// so refills remain anchored even after playback advances through the queue.
#[derive(Clone, Debug)]
pub(crate) struct RadioFill {
    pub(crate) generation: u64,
    pub(crate) seed: Track,
    pub(crate) current_index: usize,
    pub(crate) current_uri: String,
    pub(crate) current_token: u64,
}

fn shift_indices_on_insert(indices: &mut HashSet<usize>, first: usize, count: usize) {
    if count == 0 {
        return;
    }
    let shifted: HashSet<_> = indices
        .iter()
        .copied()
        .map(|index| if index >= first { index + count } else { index })
        .collect();
    *indices = shifted;
}

fn shift_indices_on_remove(indices: &mut HashSet<usize>, removed: usize) {
    let existing: Vec<_> = indices.iter().copied().collect();
    indices.clear();
    for index in existing {
        if index < removed {
            indices.insert(index);
        } else if index > removed {
            indices.insert(index - 1);
        }
    }
}

fn shift_indices_on_move(indices: &mut HashSet<usize>, from: usize, to: usize) {
    if from == to {
        return;
    }
    let moved: HashSet<_> = indices
        .iter()
        .copied()
        .map(|index| {
            if index == from {
                to
            } else if from < to && index > from && index <= to {
                index - 1
            } else if to < from && index >= to && index < from {
                index + 1
            } else {
                index
            }
        })
        .collect();
    *indices = moved;
}

fn shift_resume_on_insert(indices: &mut Vec<usize>, first: usize, count: usize) {
    if count == 0 {
        return;
    }
    for index in indices {
        if *index >= first {
            *index += count;
        }
    }
}

fn shift_resume_on_remove(indices: &mut Vec<usize>, removed: usize) {
    indices.retain(|index| *index != removed);
    for index in indices {
        if *index > removed {
            *index -= 1;
        }
    }
}

fn shift_resume_on_move(indices: &mut Vec<usize>, from: usize, to: usize) {
    if from == to {
        return;
    }
    for index in indices {
        if *index == from {
            *index = to;
        } else if from < to && *index > from && *index <= to {
            *index -= 1;
        } else if to < from && *index >= to && *index < from {
            *index += 1;
        }
    }
}

fn playable_song_key(item: &Playable) -> Option<String> {
    let track = item.track()?;
    let key = crate::recommendations::engine::song_key(&track);
    (!key.is_empty()).then_some(key)
}

fn same_track_identity(left: &Track, right: &Playable) -> bool {
    let Some(right) = right.track() else {
        return false;
    };
    left.uri == right.uri
        || left
            .id
            .as_ref()
            .zip(right.id.as_ref())
            .is_some_and(|(left_id, right_id)| !left_id.is_empty() && left_id == right_id)
}

fn automatic_session_excluded(
    queue: &[Playable],
    radio_generated: &HashSet<usize>,
    session_played: &HashSet<String>,
    session_song_keys: &HashSet<String>,
) -> HashSet<usize> {
    radio_generated
        .iter()
        .copied()
        .filter(|index| {
            queue.get(*index).is_some_and(|item| {
                session_played.contains(&item.uri())
                    || playable_song_key(item).is_some_and(|key| session_song_keys.contains(&key))
            })
        })
        .collect()
}

impl Queue {
    /// Build a queue with a fixed state, bypassing the persisted queue state.
    #[cfg(test)]
    pub fn new_for_test(
        tracks: Vec<Playable>,
        current: Option<usize>,
        spotify: Spotify,
        cfg: Arc<Config>,
        library: Arc<Library>,
    ) -> Self {
        Self {
            queue: Arc::new(RwLock::new(tracks)),
            random_order: RwLock::new(None),
            current_track: RwLock::new(current),
            spotify,
            cfg,
            library,
            listening: Mutex::new(crate::recommendations::tracker::Tracker::new(
                crate::recommendations::history::shared(),
            )),
            session_played: Mutex::new(HashSet::new()),
            session_song_keys: Mutex::new(HashSet::new()),
            explicit_queued: RwLock::new(HashSet::new()),
            radio_generated: RwLock::new(HashSet::new()),
            active_radio: RwLock::new(HashSet::new()),
            rpc_mutation: Mutex::new(0),
            played_indices: RwLock::new(HashSet::new()),
            current_token: RwLock::new(0),
            resume_context: RwLock::new(Vec::new()),
            resume_context_valid: RwLock::new(false),
            radio: Mutex::new(RadioState::default()),
            last_skip: Mutex::new(None),
        }
    }

    pub fn new(spotify: Spotify, cfg: Arc<Config>, library: Arc<Library>) -> Self {
        let queue_state = cfg.state().queuestate.clone();
        let queue_len = queue_state.queue.len();
        let current_track = queue_state.current_track.filter(|index| *index < queue_len);
        let random_order = queue_state.random_order.and_then(|mut order| {
            let mut seen = HashSet::new();
            order.retain(|index| *index < queue_len && seen.insert(*index));
            (order.len() == queue_len).then_some(order)
        });
        let explicit_queued = queue_state
            .explicit_queued
            .into_iter()
            .filter(|index| *index < queue_len)
            .collect();
        let radio_generated = queue_state
            .radio_generated
            .into_iter()
            .filter(|index| *index < queue_len)
            .collect();
        let resume_context: Vec<usize> = queue_state
            .resume_context
            .into_iter()
            .filter(|index| *index < queue_len)
            .collect();
        let resume_context_valid = queue_state.resume_context_valid || !resume_context.is_empty();

        Self {
            queue: Arc::new(RwLock::new(queue_state.queue)),
            spotify: spotify.clone(),
            current_track: RwLock::new(current_track),
            random_order: RwLock::new(random_order),
            cfg,
            library,
            listening: Mutex::new(crate::recommendations::tracker::Tracker::new(
                crate::recommendations::history::shared(),
            )),
            session_played: Mutex::new(HashSet::new()),
            session_song_keys: Mutex::new(HashSet::new()),
            explicit_queued: RwLock::new(explicit_queued),
            radio_generated: RwLock::new(radio_generated),
            active_radio: RwLock::new(HashSet::new()),
            rpc_mutation: Mutex::new(0),
            played_indices: RwLock::new(HashSet::new()),
            current_token: RwLock::new(0),
            resume_context: RwLock::new(resume_context),
            resume_context_valid: RwLock::new(resume_context_valid),
            radio: Mutex::new(RadioState::default()),
            last_skip: Mutex::new(None),
        }
    }

    /// The currently playing item from `self.queue`.
    pub fn get_current(&self) -> Option<Playable> {
        self.get_current_index()
            .and_then(|index| self.queue.read().unwrap().get(index).cloned())
    }

    /// The index of the currently playing item from `self.queue`.
    pub fn get_current_index(&self) -> Option<usize> {
        *self.current_track.read().unwrap()
    }

    pub fn get_library(&self) -> Arc<Library> {
        self.library.clone()
    }

    /// The amount of items in `self.queue`.
    pub fn len(&self) -> usize {
        self.queue.read().unwrap().len()
    }

    /// Get the spotify session.
    pub fn get_spotify(&self) -> Spotify {
        self.spotify.clone()
    }
}

/// Send a notification using the desktops default notification method.
///
/// `summary_txt`: A short title for the notification.
/// `body_txt`: The actual content of the notification.
/// `cover_url`: A URL to an image to show in the notification.
/// `notification_id`: Unique id for a notification, that can be used to operate
/// on a previous notification (for example to close it).
#[cfg(feature = "notify")]
pub fn send_notification(summary_txt: &str, body_txt: &str, cover_url: Option<String>) {
    let mut n = Notification::new();
    n.appname(resonance::BIN_NAME)
        .summary(summary_txt)
        .body(body_txt);

    // album cover image
    if let Some(u) = cover_url {
        let path = crate::utils::cache_path_for_url(u.to_string());
        if !path.exists()
            && let Err(e) = crate::utils::download(u, path.clone())
        {
            log::error!("Failed to download cover: {e}");
        }
        n.icon(path.to_str().unwrap());
    }

    // XDG desktop entry hints
    #[cfg(all(unix, not(target_os = "macos")))]
    n.urgency(notify_rust::Urgency::Low)
        .hint(notify_rust::Hint::Transient(true))
        .hint(notify_rust::Hint::DesktopEntry("resonance".into()));

    match n.show() {
        Ok(handle) => {
            // only available for XDG
            #[cfg(all(unix, not(target_os = "macos")))]
            info!("Created notification: {}", handle.id());
            #[cfg(not(all(unix, not(target_os = "macos"))))]
            drop(handle);
        }
        Err(e) => log::error!("Failed to send notification cover: {e}"),
    }
}

